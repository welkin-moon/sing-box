#!/usr/bin/env python3
"""Write isolated, private, per-subscriber sing-box canary JSON configurations.

Never publish these files over unauthenticated HTTP. The source bundle is a
root-only file generated by render_tcp_brutal_canary.py on the same VPS.
"""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import re
import tempfile


def compose(outbounds: dict[str, dict]) -> dict:
    if not isinstance(outbounds, dict) or not outbounds:
        raise ValueError('No candidate family outbounds')
    order = [family for family in ('dual', 'v4', 'v6') if family in outbounds]
    if len(order) != len(outbounds):
        raise ValueError('Unexpected network family in source')
    entries = []
    for family in order:
        outbound = outbounds[family]
        if outbound.get('type') != 'vless' or not outbound.get('uuid'):
            raise ValueError('VLESS user identity missing')
        tls = outbound.get('tls', {})
        mux = outbound.get('multiplex', {})
        if tls.get('enabled') is not True or tls.get('insecure') is True:
            raise ValueError('TLS verification must remain active')
        if mux.get('enabled') is not True or mux.get('brutal', {}).get('enabled') is not True:
            raise ValueError('TCP Brutal Multiplex settings are mandatory')
        if outbound.get('flow'):
            raise ValueError('XTLS-Vision flow must not be combined with Multiplex')
        entries.append(outbound)
    names = [item['tag'] for item in entries]
    if len(set(names)) != len(names):
        raise ValueError('Duplicate candidate node tags')
    return {
        'log': {'level': 'warn'},
        'dns': {'servers': [{'type': 'local', 'tag': 'dns-local'}], 'final': 'dns-local'},
        'inbounds': [{'type': 'mixed', 'tag': 'mixed-in',
                      'listen': '127.0.0.1', 'listen_port': 1080}],
        'outbounds': [
            {'type': 'selector', 'tag': 'proxy', 'outbounds': names,
             'default': names[0]},
            *entries, {'type': 'direct', 'tag': 'direct'}
        ],
        'route': {'final': 'proxy', 'default_domain_resolver': 'dns-local'}
    }


def export(bundle: dict, dest: Path) -> dict:
    sources = bundle.get('client_canary_outbounds_by_user')
    if not isinstance(sources, dict) or not sources:
        raise ValueError('Per-user bundle mapping required')
    dest.mkdir(parents=True, exist_ok=True, mode=0o700)
    os.chmod(dest, 0o700)
    written = []
    for name, outbound_map in sorted(sources.items()):
        if not re.fullmatch(r'ss[1-9][0-9]*', name):
            raise ValueError('Unrecognized subscriber name')
        config = compose(outbound_map)
        # Atomic mode-0600 promotion. Files never contain other users' UUIDs.
        fd, temporary = tempfile.mkstemp(prefix='.' + name + '-', suffix='.json', dir=dest)
        try:
            with os.fdopen(fd, 'w', encoding='utf-8') as handle:
                json.dump(config, handle, indent=2)
                handle.write('\n')
            os.chmod(temporary, 0o600)
            os.replace(temporary, dest / (name + '.json'))
        finally:
            if os.path.exists(temporary):
                os.unlink(temporary)
        written.append(name)
    return {'written_users': written, 'count': len(written),
            'warning': 'Root-only files staged; no global subscription publisher configured'}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument('--bundle', type=Path, required=True)
    ap.add_argument('--out-dir', type=Path, required=True)
    args = ap.parse_args()
    data = json.loads(args.bundle.read_text(encoding='utf-8'))
    print(json.dumps(export(data, args.out_dir), sort_keys=True))


if __name__ == '__main__':
    main()
